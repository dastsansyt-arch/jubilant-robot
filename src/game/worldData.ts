export const COUNTRY_UNIVERSITIES_PACKS: CountryUniversityPack[] = RAW_COUNTRY_TOP10.map((pack) => ({
  countryCode: pack.countryCode,
  countryName: pack.countryName,
  flagCode: pack.flagCode,
  languageCode: pack.languageCode,
  examName: pack.examName,
  universities: pack.items.map(([name, diplomaLabel, primarySkill], idx) => {
    const rank = idx + 1;
    // Rank 1 requires higher school grade (10.5/12) and C1 (5); Rank 10 requires 7.2/12 and B1/B2 (3-4)
    const minSchoolGrade = Number((10.6 - idx * 0.34).toFixed(1));
    const requiredLanguageLevel = rank <= 3 ? 5 : rank <= 7 ? 4 : 3;
    const tuitionCost = Math.round(pack.baseTuition * (1.45 - idx * 0.08));
    const requiredIntellect = Math.max(24, 62 - idx * 4);
    const skillBonus = Math.max(14, 28 - idx);
    return {
      id: `uni_${pack.countryCode.toLowerCase()}_${rank}`,
      name,
      institutionType: 'Университет',
      regionGroup: pack.regionGroup,
      cityOrCountry: `${pack.countryName} · Топ #${rank}`,
      countryCode: pack.countryCode,
      countryName: pack.countryName,
      rankInCountry: rank,
      worldRankLabel: `Топ-${rank} (${pack.countryName})`,
      durationYears: 4,
      tuitionCost,
      requiredIntellect,
      minSchoolGrade,
      requiredLanguageCode: pack.languageCode,
      requiredLanguageLevel,
      primarySkill,
      skillBonus,
      diplomaLabel,
    };
  }),
}));

