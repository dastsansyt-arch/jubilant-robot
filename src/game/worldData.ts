// Era / Year Release Helper so starting in a chosen year unlocks matching tech & vehicles
export function getItemReleaseYear(itemId: string, price: number): number {
  const hash = itemId.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  if (itemId.includes('rtx_5090') || itemId.includes('iphone_16') || itemId.includes('cybertruck')) return 2024;
  if (itemId.includes('rtx_4070') || itemId.includes('macbook_m3') || itemId.includes('ps5') || itemId.includes('vision_pro')) return 2022;
  if (itemId.includes('tesla') || itemId.includes('taycan') || itemId.includes('ryzen_7')) return 2019;
  if (itemId.includes('supra_mk4') || itemId.includes('skyline_r34') || itemId.includes('lancer_evo9')) return 1998;
  if (itemId.includes('lada') || itemId.includes('daewoo') || itemId.includes('bicycle')) return 1985;
  if (price <= 400) return 1988 + (hash % 10);
  if (price <= 1500) return 1996 + (hash % 14);
  if (price <= 15000) return 2002 + (hash % 15);
  return 2008 + (hash % 16);
}




