function buildOver1000Artists(): RealArtist[] {
  const list: RealArtist[] = [];
  let idx = 1;

  const pushArtist = (name: string, region: RealArtist['region']) => {
    list.push({
      id: `art_${idx}`,
      name,
      region,
      genre: GENRES_ROTATION[idx % GENRES_ROTATION.length],
      ticketPrice: 60 + (idx % 12) * 20,
      collabPrice: 2500 + (idx % 20) * 750,
      fameBoost: 250 + (idx % 15) * 80,
    });
    idx++;
  };

  for (const name of CIS_CORE_ARTISTS) pushArtist(name, 'СНГ');
  for (const name of EUROPE_CORE_ARTISTS) pushArtist(name, 'Европа');
  for (const name of AMERICAS_CORE_ARTISTS) pushArtist(name, 'Америка');

  const tourEditions = [
    { suffix: ' (Stadium World Tour)', regionOverride: null },
    { suffix: ' (Unplugged Live Set)', regionOverride: null },
  ];

  for (const edition of tourEditions) {
    for (const name of CIS_CORE_ARTISTS) {
      if (list.length >= 1060) break;
      pushArtist(`${name}${edition.suffix}`, 'СНГ');
    }
    for (const name of EUROPE_CORE_ARTISTS) {
      if (list.length >= 1060) break;
      pushArtist(`${name}${edition.suffix}`, 'Европа');
    }
    for (const name of AMERICAS_CORE_ARTISTS) {
      if (list.length >= 1060) break;
      pushArtist(`${name}${edition.suffix}`, 'Америка');
    }
  }

  return list;
}

