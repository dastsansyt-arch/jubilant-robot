export function generateSecondaryEducationForCity(
  city: CityOption,
  seedOffset = 0
): {
  secondarySchoolName: string;
  localColleges: UniversityProgram[];
} {
  const hash =
    city.id.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0) + seedOffset * 17;

  const schoolTypePool = ['Общеобразовательная школа', 'Гимназия', 'Лицей', 'Специализированная школа'];
  const schoolNum = ((hash * 13) % 185) + 1;
  const secondarySchoolName = `${schoolTypePool[hash % schoolTypePool.length]} №${schoolNum} г. ${city.name}`;

  const collegeTemplates: {
    prefix: string;
    primarySkill: keyof Skills;
    diploma: string;
    baseCost: number;
  }[] = [
    {
      prefix: 'Политехнический колледж компьютерных систем и связи',
      primarySkill: 'intellect',
      diploma: 'Младший специалист по программированию и сетям',
      baseCost: 950,
    },
    {
      prefix: 'Финансово-экономический и банковский колледж',
      primarySkill: 'finance',
      diploma: 'Специалист банковского дела, учёта и торговли',
      baseCost: 1100,
    },
    {
      prefix: 'Медицинский и фармацевтический колледж',
      primarySkill: 'intellect',
      diploma: 'Диплом фельдшера и фармацевта',
      baseCost: 1050,
    },
    {
      prefix: 'Автотранспортный и машиностроительный техникум',
      primarySkill: 'urbex',
      diploma: 'Техник-механик автоспорта и электротранспорта',
      baseCost: 800,
    },
    {
      prefix: 'Колледж архитектуры, дизайна, кино и медиа',
      primarySkill: 'creativity',
      diploma: 'Дизайнер интерьеров и мультимедиа-продюсер',
      baseCost: 980,
    },
    {
      prefix: 'Олимпийский спортивно-педагогический колледж',
      primarySkill: 'strength',
      diploma: 'Инструктор силового спорта и реабилитации',
      baseCost: 750,
    },
  ];

  const localColleges: UniversityProgram[] = collegeTemplates.map((tpl, idx) => {
    const colNumber = ((hash + (idx + 1) * 29) % 140) + 1;
    return {
      id: `col_rand_${city.id}_${colNumber}_${idx}`,
      name: `${tpl.prefix} №${colNumber} (г. ${city.name})`,
      institutionType: idx % 2 === 0 ? 'Колледж' : 'Техникум / Лицей',
      regionGroup: 'Среднее образование (Колледжи и Техникумы)',
      cityOrCountry: `${city.name}, ${city.country}`,
      worldRankLabel: `Гос. лицензия №${colNumber} · Среднее проф. образование`,
      durationYears: 2,
      tuitionCost: Math.round(tpl.baseCost * Math.max(0.7, city.economyMultiplier * 0.85)),
      requiredIntellect: 12 + idx * 2,
      primarySkill: tpl.primarySkill,
      skillBonus: 18 + (idx % 3) * 2,
      diplomaLabel: `${tpl.diploma} (Колледж №${colNumber})`,
    };
  });

  return { secondarySchoolName, localColleges };
}

