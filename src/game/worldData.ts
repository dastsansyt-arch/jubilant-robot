export function getNamePoolForCountry(countryCode: string) {
  if (COUNTRY_NAME_POOLS[countryCode]) return COUNTRY_NAME_POOLS[countryCode];
  if (countryCode === 'BY') return COUNTRY_NAME_POOLS.RU;
  if (['AR', 'BR', 'CO', 'CL', 'PT'].includes(countryCode)) return COUNTRY_NAME_POOLS.ES;
  if (['AT', 'CH', 'NL', 'SE', 'NO', 'FI', 'DK', 'IS', 'CZ', 'HU', 'RO', 'EE', 'LV', 'LT'].includes(countryCode)) return COUNTRY_NAME_POOLS.DE;
  if (['MC', 'BE'].includes(countryCode)) return COUNTRY_NAME_POOLS.FR;
  if (['GR', 'CY', 'ME', 'HR', 'RS', 'BG'].includes(countryCode)) return COUNTRY_NAME_POOLS.IT;
  if (['CN', 'SG', 'TH', 'AE', 'ID', 'MV', 'TR', 'GE'].includes(countryCode)) return COUNTRY_NAME_POOLS.JP;
  return COUNTRY_NAME_POOLS.US;
}

export function generateRandomPersonName(
  countryCode: string,
  gender: 'male' | 'female' = 'male',
  seed: number = Math.floor(Math.random() * 1000)
): string {
  const pool = getNamePoolForCountry(countryCode);
  const firstList = gender === 'male' ? pool.maleFirst : pool.femaleFirst;
  const first = firstList[Math.abs(seed) % firstList.length];
  const lastIdx = Math.abs(seed * 3 + 1) % pool.surnames.length;
  const last =
    gender === 'female' && pool.femaleSurnames
      ? pool.femaleSurnames[lastIdx % pool.femaleSurnames.length]
      : pool.surnames[lastIdx];
  return `${first} ${last}`;
}

